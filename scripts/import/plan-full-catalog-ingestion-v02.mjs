function asText(value) {
  return String(value ?? '').trim()
}

function normalizeWhitespace(value) {
  return asText(value).replace(/\s+/gu, ' ')
}

function normalizeTitle(value) {
  return normalizeWhitespace(value)
    .toLowerCase()
    .normalize('NFKC')
    .replace(/[\u3000\s]+/gu, ' ')
    .replace(/[「」『』【】\[\]（）()〈〉《》]/gu, '')
    .replace(/[,:;，。！？!?.·・~〜ー—–_\-]+/gu, ' ')
    .replace(/\s+/gu, ' ')
    .trim()
}

function normalizeSourceRecordKey(value) {
  return normalizeWhitespace(value).toLowerCase()
}

function inc(map, key, amount = 1) {
  const normalized = asText(key) || 'missing'
  map[normalized] = (map[normalized] || 0) + amount
}

function sortCountObject(value) {
  return Object.fromEntries(Object.entries(value).sort((a, b) => {
    if (b[1] !== a[1]) return b[1] - a[1]
    return a[0].localeCompare(b[0])
  }))
}

function mdCell(value) {
  return String(value ?? '').replace(/\|/gu, '\\|').replace(/\n/gu, ' ')
}

async function readJsonl(filePath, onRow) {
  const stream = fs.createReadStream(filePath, { encoding: 'utf8' })
  const rl = readline.createInterface({ input: stream, crlfDelay: Infinity })
  let rows = 0
  let failed = 0

  for await (const line of rl) {
    const text = line.trim()
    if (!text) continue

    try {
      await onRow(JSON.parse(text), rows)
    } catch {
      failed += 1
    }

    rows += 1
  }

  return { rows, failed }
}

async function requestJson(url, options = {}) {
  const response = await fetch(url, {
    ...options,
    headers: {
      'Content-Type': 'application/json',
      ...(options.headers || {}),
    },
  })

  const text = await response.text()
  let payload = null

  try {
    payload = text ? JSON.parse(text) : null
  } catch {
    payload = { raw: text }
  }

  if (!response.ok) {
    const detail = payload ? JSON.stringify(payload, null, 2) : text
    throw new Error(`HTTP ${response.status} ${response.statusText}\n${detail}`)
  }

  return payload
}

async function login(baseUrl, email, password) {
  const result = await requestJson(`${baseUrl}/api/users/login`, {
    method: 'POST',
    body: JSON.stringify({ email, password }),
  })

  if (!result?.token) throw new Error('Payload login succeeded but did not return a token.')
  return result.token
}

function authHeaders(token) {
  return { Authorization: `JWT ${token}` }
}

async function fetchAllWorks(baseUrl, token) {
  const docs = []
  let page = 1
  let totalPages = 1
  let totalDocs = 0

  while (page <= totalPages) {
    const result = await requestJson(`${baseUrl}/api/works?limit=${PAGE_LIMIT}&page=${page}&depth=0`, {
      headers: authHeaders(token),
    })

    totalPages = Number(result.totalPages || 1)
    totalDocs = Number(result.totalDocs || 0)
    docs.push(...(Array.isArray(result.docs) ? result.docs : []))
    page += 1
  }

  return { totalDocs, docs }
}

function splitListLike(value) {
  if (Array.isArray(value)) return value.flatMap(splitListLike)
  if (!value) return []

  return String(value)
    .split(/[;|,\n]/u)
    .map(normalizeWhitespace)
    .filter(Boolean)
}

function collectWorkTitles(work) {
  const values = [work.title, work.name, work.originalTitle, work.localizedTitle, work.displayTitle]

  for (const key of ['aliases', 'alias', 'altTitles', 'alternativeTitles', 'synonyms']) {
    values.push(...splitListLike(work?.[key]))
  }

  return [...new Set(values.map(normalizeWhitespace).filter(Boolean))]
}

function collectWorkSourceKeys(work) {
  const keys = []
  const chosenBaseSource = normalizeWhitespace(work.chosenBaseSource).toLowerCase()

  for (const key of ['sourceRecordKey', 'sourceKey', 'sourceId', 'externalId']) {
    const value = normalizeWhitespace(work?.[key])
    if (value) {
      keys.push(value)
      if (chosenBaseSource && !value.toLowerCase().startsWith(`${chosenBaseSource}:`)) {
        keys.push(`${chosenBaseSource}:${value}`)
      }
    }
  }

  const candidateSources = work.candidateSources ?? work.sourceCandidates ?? work.sources
  if (Array.isArray(candidateSources)) {
    for (const item of candidateSources) {
      if (typeof item === 'string') keys.push(item)
      else if (item && typeof item === 'object') {
        for (const key of ['sourceRecordKey', 'sourceKey', 'sourceId', 'externalId', 'id']) {
          const value = normalizeWhitespace(item[key])
          if (value) keys.push(value)
        }
        const sourceName = normalizeWhitespace(item.sourceName || item.source || item.provider).toLowerCase()
        const sourceId = normalizeWhitespace(item.sourceId || item.externalId || item.id)
        if (sourceName && sourceId) keys.push(`${sourceName}:${sourceId}`)
      }
    }
  }

  return [...new Set(keys.map(normalizeSourceRecordKey).filter(Boolean))]
}

function buildWorkIndex(works) {
  const byTitle = new Map()
  const bySourceKey = new Map()

  for (const work of works) {
    for (const title of collectWorkTitles(work)) {
      const normalized = normalizeTitle(title)
      if (!normalized) continue
      if (!byTitle.has(normalized)) byTitle.set(normalized, [])
      byTitle.get(normalized).push(work)
    }

    for (const sourceKey of collectWorkSourceKeys(work)) {
      if (!bySourceKey.has(sourceKey)) bySourceKey.set(sourceKey, [])
      bySourceKey.get(sourceKey).push(work)
    }
  }

  return { byTitle, bySourceKey }
}

async function maybeFetchPayload(baseUrl, noPayload) {
  const email = process.env.PAYLOAD_SEED_EMAIL
  const password = process.env.PAYLOAD_SEED_PASSWORD

  if (noPayload) {
    return { skipped: true, reason: '--no-payload was provided', works: [] }
  }

  if (!email || !password) {
    return { skipped: true, reason: 'PAYLOAD_SEED_EMAIL or PAYLOAD_SEED_PASSWORD is missing', works: [] }
  }

  console.error(`[plan-v02] logging in to ${baseUrl} ...`)
  const token = await login(baseUrl, email, password)

  console.error('[plan-v02] fetching works from Payload ...')
  const { totalDocs, docs } = await fetchAllWorks(baseUrl, token)

  return { skipped: false, baseUrl, totalDocs, works: docs }
}

function compactWork(work) {
  if (!work) return null
  return {
    id: work.id,
    title: work.title || work.name || '',
    siteId: work.siteId || '',
    slug: work.slug || '',
    importBatch: work.importBatch || '',
    chosenBaseSource: work.chosenBaseSource || '',
    mediaType: work.mediaType || '',
    mediaGroup: work.mediaGroup || '',
  }
}

function compactRecord(record) {
  return {
    sourceRecordKey: record.sourceRecordKey || '',
    sourceName: record.sourceName || '',
    sourceId: record.sourceId || '',
    sourceTitle: record.sourceTitle || '',
    sourceMediaType: record.sourceMediaType || '',
    eligibilityStatus: record.eligibilityStatus || '',
    rawPath: record.rawPath || '',
  }
}

function stripTrailingPunctuation(value) {
  return normalizeWhitespace(value)
    .replace(/[\s:：,，.。;；~〜ー—–_\-]+$/u, '')
    .trim()
}

function inferParentTitle(title) {
  const original = normalizeWhitespace(title)
  if (!original) return ''

  const patterns = [
    /^(?<parent>.+?)\s*(?:vol(?:ume)?\.?|volume)\s*\d{1,3}\b.*$/iu,
    /^(?<parent>.+?)\s+\d{1,3}\s*(?:巻|卷|册|冊|話|话)\b.*$/iu,
    /^(?<parent>.+?)\s*第\s*\d{1,3}\s*(?:巻|卷|册|冊|話|话)\b.*$/iu,
    /^(?<parent>.+?)\s+[\[(（【]?\d{1,3}[\])）】]?.*$/u,
    /^(?<parent>.+?)\s*(?:上巻|下巻|前篇|後篇|后篇|番外|外伝|外传).*$/u,
  ]

  for (const pattern of patterns) {
    const match = original.match(pattern)
    const parent = stripTrailingPunctuation(match?.groups?.parent || '')
    if (parent && parent.length >= 2 && parent !== original) return parent
  }

  return ''
}

function looksVolumeLike(title) {
  const text = normalizeWhitespace(title)
  if (!text) return false

  return /(?:\bvol(?:ume)?\.?\s*\d+\b|volume\s*\d+|第\s*\d+\s*[卷巻册冊話话]|\d+\s*[卷巻册冊]|\s\d{1,3}\s|\s\d{1,3}$|上巻|下巻|前篇|後篇|后篇|番外|外伝|外传)/iu.test(text)
}

function looksEditionLike(record) {
  const title = normalizeWhitespace(record.sourceTitle)
  const rawPath = normalizeWhitespace(record.rawPath).toLowerCase()
  const url = normalizeWhitespace(record.sourceUrl).toLowerCase()

  return /(?:edition|revised|digital|ebook|paperback|hardcover|switch|ps4|ps5|steam|dlc|bundle|limited|remaster|remastered|完全版|新装版|電子|文庫|特装版|限定版|移植版)/iu.test(title)
    || /(?:steam|release|edition|package|appid)/iu.test(rawPath)
    || /store\.steampowered\.com/iu.test(url)
}

function detectBoundary(record) {
  const title = normalizeWhitespace(record.sourceTitle)
  const parentCandidateTitle = inferParentTitle(title)
  const volumeLike = looksVolumeLike(title)
  const editionLike = looksEditionLike(record)

  if (volumeLike || parentCandidateTitle) {
    return {
      entityBoundary: 'child_candidate',
      boundaryReason: volumeLike ? 'volume_like_title' : 'parent_title_inferred',
      parentCandidateTitle,
      parentCandidateNormalizedTitle: normalizeTitle(parentCandidateTitle),
      volumeLike,
      editionLike,
    }
  }

  if (editionLike) {
    return {
      entityBoundary: 'edition_or_release_candidate',
      boundaryReason: 'edition_or_release_like_source_row',
      parentCandidateTitle: '',
      parentCandidateNormalizedTitle: '',
      volumeLike,
      editionLike,
    }
  }

  return {
    entityBoundary: 'work_candidate',
    boundaryReason: 'stable_work_candidate',
    parentCandidateTitle: '',
    parentCandidateNormalizedTitle: '',
    volumeLike,
    editionLike,
  }
}

function buildSourceRecordContext(records) {
  const byNormalizedTitle = new Map()

  for (const record of records) {
    const normalized = normalizeTitle(record.sourceTitle)
    if (!normalized) continue
    if (!byNormalizedTitle.has(normalized)) byNormalizedTitle.set(normalized, [])
    byNormalizedTitle.get(normalized).push(record)
  }

  return { byNormalizedTitle }
}

function findSourceParentCandidates(boundary, sourceRecordContext) {
  const normalized = boundary.parentCandidateNormalizedTitle
  if (!normalized) return []
  return (sourceRecordContext.byNormalizedTitle.get(normalized) || []).slice(0, 10).map(compactRecord)
}

function planRecord(record, context) {
  const sourceName = normalizeWhitespace(record.sourceName)
  const sourceTitle = normalizeWhitespace(record.sourceTitle)
  const sourceRecordKey = normalizeSourceRecordKey(record.sourceRecordKey)
  const normalizedTitle = normalizeTitle(sourceTitle)
  const eligibilityStatus = normalizeWhitespace(record.eligibilityStatus)
  const boundary = detectBoundary(record)

  const base = {
    sourceRecordKey: record.sourceRecordKey,
    sourceName,
    sourceId: record.sourceId || '',
    sourceUrl: record.sourceUrl || '',
    sourceTitle,
    sourceMediaType: record.sourceMediaType || 'unknown',
    eligibilityStatus,
    rawPath: record.rawPath || '',
    entityBoundary: boundary.entityBoundary,
    boundaryReason: boundary.boundaryReason,
    parentCandidateTitle: boundary.parentCandidateTitle,
    parentCandidateNormalizedTitle: boundary.parentCandidateNormalizedTitle,
    volumeLike: boundary.volumeLike,
    editionLike: boundary.editionLike,
  }

  if (eligibilityStatus === 'evidence_only') {
    return {
      ...base,
      action: 'evidence_only',
      reason: record.excludeReason || 'source_record_marked_evidence_only',
      confidence: 'high',
      matchedWorks: [],
      parentCandidateSourceRecords: [],
    }
  }

  if (eligibilityStatus === 'quarantine') {
    return {
      ...base,
      action: 'quarantine',
      reason: record.excludeReason || 'source_record_marked_quarantine',
      confidence: 'high',
      matchedWorks: [],
      parentCandidateSourceRecords: [],
    }
  }

  if (eligibilityStatus === 'not_catalog') {
    return {
      ...base,
      action: 'not_catalog',
      reason: record.excludeReason || 'source_record_marked_not_catalog',
      confidence: 'high',
      matchedWorks: [],
      parentCandidateSourceRecords: [],
    }
  }

  if (context.payloadSkipped) {
    if (boundary.entityBoundary === 'child_candidate') {
      return {
        ...base,
        action: 'create_child_entity_needs_policy',
        reason: 'volume_or_child_candidate_without_payload_comparison',
        confidence: boundary.parentCandidateTitle ? 'medium' : 'low',
        matchedWorks: [],
        parentCandidateSourceRecords: findSourceParentCandidates(boundary, context.sourceRecordContext),
      }
    }

    if (boundary.entityBoundary === 'edition_or_release_candidate') {
      return {
        ...base,
        action: 'create_volume_or_edition_needs_policy',
        reason: 'edition_or_release_candidate_without_payload_comparison',
        confidence: 'low',
        matchedWorks: [],
        parentCandidateSourceRecords: [],
      }
    }

    return {
      ...base,
      action: 'needs_payload_comparison',
      reason: context.payloadSkippedReason,
      confidence: 'low',
      matchedWorks: [],
      parentCandidateSourceRecords: [],
    }
  }

  const sourceKeyMatches = sourceRecordKey ? context.workIndex.bySourceKey.get(sourceRecordKey) || [] : []

  if (sourceKeyMatches.length === 1) {
    return {
      ...base,
      action: 'link_existing_work_source_key',
      reason: 'exact_source_record_key_match',
      confidence: 'high',
      matchedWorks: [compactWork(sourceKeyMatches[0])],
      parentCandidateSourceRecords: [],
    }
  }

  if (sourceKeyMatches.length > 1) {
    return {
      ...base,
      action: 'identity_conflict_source_key',
      reason: 'source_record_key_matches_multiple_works',
      confidence: 'medium',
      matchedWorks: sourceKeyMatches.slice(0, 10).map(compactWork),
      parentCandidateSourceRecords: [],
    }
  }

  const titleMatches = normalizedTitle ? context.workIndex.byTitle.get(normalizedTitle) || [] : []

  if (titleMatches.length === 1) {
    return {
      ...base,
      action: 'link_existing_work_exact_title',
      reason: 'exact_normalized_title_match',
      confidence: 'medium',
      matchedWorks: [compactWork(titleMatches[0])],
      parentCandidateSourceRecords: [],
    }
  }

  if (titleMatches.length > 1) {
    return {
      ...base,
      action: 'possible_duplicate_title',
      reason: 'normalized_title_matches_multiple_works',
      confidence: 'low',
      matchedWorks: titleMatches.slice(0, 10).map(compactWork),
      parentCandidateSourceRecords: [],
    }
  }

  if (boundary.entityBoundary === 'child_candidate') {
    const parentMatches = boundary.parentCandidateNormalizedTitle
      ? context.workIndex.byTitle.get(boundary.parentCandidateNormalizedTitle) || []
      : []
    const sourceParentCandidates = findSourceParentCandidates(boundary, context.sourceRecordContext)

    if (parentMatches.length === 1) {
      return {
        ...base,
        action: 'link_to_parent_work_candidate',
        reason: 'volume_like_row_parent_title_matches_existing_work',
        confidence: 'medium',
        matchedWorks: [compactWork(parentMatches[0])],
        parentCandidateSourceRecords: sourceParentCandidates,
      }
    }

    if (parentMatches.length > 1) {
      return {
        ...base,
        action: 'possible_parent_duplicate_title',
        reason: 'volume_like_row_parent_title_matches_multiple_works',
        confidence: 'low',
        matchedWorks: parentMatches.slice(0, 10).map(compactWork),
        parentCandidateSourceRecords: sourceParentCandidates,
      }
    }

    return {
      ...base,
      action: 'create_child_entity_needs_policy',
      reason: sourceParentCandidates.length
        ? 'volume_like_row_has_source_parent_candidate'
        : 'volume_like_row_no_parent_work_match',
      confidence: sourceParentCandidates.length ? 'medium' : 'low',
      matchedWorks: [],
      parentCandidateSourceRecords: sourceParentCandidates,
    }
  }

  if (boundary.entityBoundary === 'edition_or_release_candidate') {
    return {
      ...base,
      action: 'create_volume_or_edition_needs_policy',
      reason: 'edition_or_release_like_source_row',
      confidence: 'low',
      matchedWorks: [],
      parentCandidateSourceRecords: [],
    }
  }

  if (eligibilityStatus === 'maybe_catalog') {
    return {
      ...base,
      action: 'create_new_work_needs_review',
      reason: 'maybe_catalog_no_existing_work_match',
      confidence: 'low',
      matchedWorks: [],
      parentCandidateSourceRecords: [],
    }
  }

  return {
    ...base,
    action: 'create_new_work',
    reason: 'eligible_for_catalog_no_existing_work_match',
    confidence: 'medium',
    matchedWorks: [],
    parentCandidateSourceRecords: [],
  }
}

function buildSummary({ recordsRead, recordsFailed, plans, payload }) {
  const byAction = {}
  const byReason = {}
  const bySource = {}
  const bySourceAction = {}
  const byMediaType = {}
  const byConfidence = {}
  const byEntityBoundary = {}
  const byBoundaryReason = {}
  const byParentCandidate = {}

  for (const plan of plans) {
    inc(byAction, plan.action)
    inc(byReason, plan.reason)
    inc(bySource, plan.sourceName)
    inc(bySourceAction, `${plan.sourceName}:${plan.action}`)
    inc(byMediaType, plan.sourceMediaType)
    inc(byConfidence, plan.confidence)
    inc(byEntityBoundary, plan.entityBoundary)
    inc(byBoundaryReason, plan.boundaryReason)
    if (plan.parentCandidateTitle) inc(byParentCandidate, plan.parentCandidateTitle)
  }

  return {
    generatedAt: new Date().toISOString(),
    version: 'v0.2',
    sourceRecordsRead: recordsRead,
    sourceRecordsFailed: recordsFailed,
    plannedRows: plans.length,
    payloadChecked: !payload.skipped,
    payloadWorks: payload.skipped ? 0 : payload.works.length,
    payloadSkippedReason: payload.skipped ? payload.reason : '',
    byAction: sortCountObject(byAction),
    byReason: sortCountObject(byReason),
    bySource: sortCountObject(bySource),
    bySourceAction: sortCountObject(bySourceAction),
    byMediaType: sortCountObject(byMediaType),
    byConfidence: sortCountObject(byConfidence),
    byEntityBoundary: sortCountObject(byEntityBoundary),
    byBoundaryReason: sortCountObject(byBoundaryReason),
    topParentCandidates: Object.fromEntries(Object.entries(sortCountObject(byParentCandidate)).slice(0, 50)),
    safety: {
      payloadWrite: false,
      postgresqlWrite: false,
      importerApply: false,
      delete: false,
    },
  }
}

function buildSamples(plans) {
  const byAction = {}
  const byEntityBoundary = {}

  for (const plan of plans) {
    if (!byAction[plan.action]) byAction[plan.action] = []
    if (byAction[plan.action].length < SAMPLE_LIMIT) byAction[plan.action].push(plan)

    if (!byEntityBoundary[plan.entityBoundary]) byEntityBoundary[plan.entityBoundary] = []
    if (byEntityBoundary[plan.entityBoundary].length < SAMPLE_LIMIT) byEntityBoundary[plan.entityBoundary].push(plan)
  }

  return { byAction, byEntityBoundary }
}

function formatCountTable(title, entries) {
  return [
    `## ${title}`,
    '',
    '| Key | Count |',
    '|---|---:|',
    ...Object.entries(entries).map(([key, count]) => `| ${mdCell(key)} | ${count} |`),
    '',
  ]
}

