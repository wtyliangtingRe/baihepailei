#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import readline from 'node:readline'

const DEFAULT_SOURCE_RECORDS = 'data_local/staging/source-records/source-records-v01.jsonl'
const DEFAULT_OUT_DIR = 'data_local/staging/full-catalog-ingestion'
const DEFAULT_URL = 'http://localhost:3000'
const PAGE_LIMIT = 100
const SAMPLE_LIMIT = 50

function parseArgs(argv) {
  const args = {}

  for (let index = 0; index < argv.length; index += 1) {
    const item = argv[index]
    if (!item.startsWith('--')) continue

    const key = item.slice(2)
    const next = argv[index + 1]

    if (!next || next.startsWith('--')) {
      args[key] = true
      continue
    }

    args[key] = next
    index += 1
  }

  return args
}

function usage() {
  console.log(`Usage:
  node scripts/import/plan-full-catalog-ingestion-v01.mjs [--source-records <jsonl>] [--out-dir <dir>] [--url http://localhost:3000] [--no-payload]

Optional environment variables for Payload API comparison:
  PAYLOAD_SEED_EMAIL
  PAYLOAD_SEED_PASSWORD

This is a read-only full catalog ingestion dry-run:
  - Reads SourceRecord JSONL generated by normalize-source-records-v01.
  - Optionally reads current Payload Works through the HTTP API.
  - Produces action plans such as create_new_work, link_existing_work_exact_title, possible_duplicate_title, evidence_only, and quarantine.
  - Writes JSONL / JSON / summary JSON / Markdown reports to data_local/staging/full-catalog-ingestion by default.

Safety:
  - No Payload write.
  - No PostgreSQL write.
  - No importer apply.
  - No delete.
  - No data_local output should be committed.
`)
}

function asText(value) {
  return String(value ?? '').trim()
}

function normalizeWhitespace(value) {
  return asText(value).replace(/\s+/gu, ' ')
}

function normalizeTitle(value) {
  return normalizeWhitespace(value)
    .toLowerCase()
    .normalize('NFKC')
    .replace(/[\u3000\s]+/gu, ' ')
    .replace(/[「」『』【】\[\]（）()〈〉《》]/gu, '')
    .replace(/[,:;，。！？!?.·・~〜ー—–_\-]+/gu, ' ')
    .replace(/\s+/gu, ' ')
    .trim()
}

function normalizeSourceRecordKey(value) {
  return normalizeWhitespace(value).toLowerCase()
}

function inc(map, key, amount = 1) {
  const normalized = asText(key) || 'missing'
  map[normalized] = (map[normalized] || 0) + amount
}

function sortCountObject(value) {
  return Object.fromEntries(Object.entries(value).sort((a, b) => {
    if (b[1] !== a[1]) return b[1] - a[1]
    return a[0].localeCompare(b[0])
  }))
}

function mdCell(value) {
  return String(value ?? '').replace(/\|/gu, '\\|').replace(/\n/gu, ' ')
}

async function readJsonl(filePath, onRow) {
  const stream = fs.createReadStream(filePath, { encoding: 'utf8' })
  const rl = readline.createInterface({ input: stream, crlfDelay: Infinity })
  let rows = 0
  let failed = 0

  for await (const line of rl) {
    const text = line.trim()
    if (!text) continue

    try {
      await onRow(JSON.parse(text), rows)
    } catch {
      failed += 1
    }

    rows += 1
  }

  return { rows, failed }
}

async function requestJson(url, options = {}) {
  const response = await fetch(url, {
    ...options,
    headers: {
      'Content-Type': 'application/json',
      ...(options.headers || {}),
    },
  })

  const text = await response.text()
  let payload = null

  try {
    payload = text ? JSON.parse(text) : null
  } catch {
    payload = { raw: text }
  }

  if (!response.ok) {
    const detail = payload ? JSON.stringify(payload, null, 2) : text
    throw new Error(`HTTP ${response.status} ${response.statusText}\n${detail}`)
  }

  return payload
}

async function login(baseUrl, email, password) {
  const result = await requestJson(`${baseUrl}/api/users/login`, {
    method: 'POST',
    body: JSON.stringify({ email, password }),
  })

  if (!result?.token) {
    throw new Error('Payload login succeeded but did not return a token.')
  }

  return result.token
}

function authHeaders(token) {
  return { Authorization: `JWT ${token}` }
}

async function fetchAllWorks(baseUrl, token) {
  const docs = []
  let page = 1
  let totalPages = 1
  let totalDocs = 0

  while (page <= totalPages) {
    const result = await requestJson(`${baseUrl}/api/works?limit=${PAGE_LIMIT}&page=${page}&depth=0`, {
      headers: authHeaders(token),
    })

    totalPages = Number(result.totalPages || 1)
    totalDocs = Number(result.totalDocs || 0)
    docs.push(...(Array.isArray(result.docs) ? result.docs : []))
    page += 1
  }

  return { totalDocs, docs }
}

function splitListLike(value) {
  if (Array.isArray(value)) return value.flatMap(splitListLike)
  if (!value) return []

  return String(value)
    .split(/[;|,\n]/u)
    .map(normalizeWhitespace)
    .filter(Boolean)
}

function collectWorkTitles(work) {
  const values = [
    work.title,
    work.name,
    work.originalTitle,
    work.localizedTitle,
    work.displayTitle,
  ]

  for (const key of ['aliases', 'alias', 'altTitles', 'alternativeTitles', 'synonyms']) {
    values.push(...splitListLike(work?.[key]))
  }

  return [...new Set(values.map(normalizeWhitespace).filter(Boolean))]
}

function collectWorkSourceKeys(work) {
  const keys = []
  const chosenBaseSource = normalizeWhitespace(work.chosenBaseSource).toLowerCase()

  for (const key of ['sourceRecordKey', 'sourceKey', 'sourceId', 'externalId']) {
    const value = normalizeWhitespace(work?.[key])
    if (value) {
      keys.push(value)
      if (chosenBaseSource && !value.toLowerCase().startsWith(`${chosenBaseSource}:`)) {
        keys.push(`${chosenBaseSource}:${value}`)
      }
    }
  }

  const candidateSources = work.candidateSources ?? work.sourceCandidates ?? work.sources
  if (Array.isArray(candidateSources)) {
    for (const item of candidateSources) {
      if (typeof item === 'string') keys.push(item)
      else if (item && typeof item === 'object') {
        for (const key of ['sourceRecordKey', 'sourceKey', 'sourceId', 'externalId', 'id']) {
          const value = normalizeWhitespace(item[key])
          if (value) keys.push(value)
        }
        const sourceName = normalizeWhitespace(item.sourceName || item.source || item.provider).toLowerCase()
        const sourceId = normalizeWhitespace(item.sourceId || item.externalId || item.id)
        if (sourceName && sourceId) keys.push(`${sourceName}:${sourceId}`)
      }
    }
  }

  return [...new Set(keys.map(normalizeSourceRecordKey).filter(Boolean))]
}

function buildWorkIndex(works) {
  const byTitle = new Map()
  const bySourceKey = new Map()

  for (const work of works) {
    for (const title of collectWorkTitles(work)) {
      const normalized = normalizeTitle(title)
      if (!normalized) continue
      if (!byTitle.has(normalized)) byTitle.set(normalized, [])
      byTitle.get(normalized).push(work)
    }

    for (const sourceKey of collectWorkSourceKeys(work)) {
      if (!bySourceKey.has(sourceKey)) bySourceKey.set(sourceKey, [])
      bySourceKey.get(sourceKey).push(work)
    }
  }

  return { byTitle, bySourceKey }
}

async function maybeFetchPayload(baseUrl, noPayload) {
  const email = process.env.PAYLOAD_SEED_EMAIL
  const password = process.env.PAYLOAD_SEED_PASSWORD

  if (noPayload) {
    return {
      skipped: true,
      reason: '--no-payload was provided',
      works: [],
    }
  }

  if (!email || !password) {
    return {
      skipped: true,
      reason: 'PAYLOAD_SEED_EMAIL or PAYLOAD_SEED_PASSWORD is missing',
      works: [],
    }
  }

  console.error(`[plan] logging in to ${baseUrl} ...`)
  const token = await login(baseUrl, email, password)

  console.error('[plan] fetching works from Payload ...')
  const { totalDocs, docs } = await fetchAllWorks(baseUrl, token)

  return {
    skipped: false,
    baseUrl,
    totalDocs,
    works: docs,
  }
}

function compactWork(work) {
  if (!work) return null
  return {
    id: work.id,
    title: work.title || work.name || '',
    siteId: work.siteId || '',
    slug: work.slug || '',
    importBatch: work.importBatch || '',
    chosenBaseSource: work.chosenBaseSource || '',
    mediaType: work.mediaType || '',
    mediaGroup: work.mediaGroup || '',
  }
}

function planRecord(record, context) {
  const sourceName = normalizeWhitespace(record.sourceName)
  const sourceTitle = normalizeWhitespace(record.sourceTitle)
  const sourceRecordKey = normalizeSourceRecordKey(record.sourceRecordKey)
  const normalizedTitle = normalizeTitle(sourceTitle)
  const eligibilityStatus = normalizeWhitespace(record.eligibilityStatus)

  const base = {
    sourceRecordKey: record.sourceRecordKey,
    sourceName,
    sourceId: record.sourceId || '',
    sourceUrl: record.sourceUrl || '',
    sourceTitle,
    sourceMediaType: record.sourceMediaType || 'unknown',
    eligibilityStatus,
    rawPath: record.rawPath || '',
  }

  if (eligibilityStatus === 'evidence_only') {
    return {
      ...base,
      action: 'evidence_only',
      reason: record.excludeReason || 'source_record_marked_evidence_only',
      confidence: 'high',
      matchedWorks: [],
    }
  }

  if (eligibilityStatus === 'quarantine') {
    return {
      ...base,
      action: 'quarantine',
      reason: record.excludeReason || 'source_record_marked_quarantine',
      confidence: 'high',
      matchedWorks: [],
    }
  }

  if (eligibilityStatus === 'not_catalog') {
    return {
      ...base,
      action: 'not_catalog',
      reason: record.excludeReason || 'source_record_marked_not_catalog',
      confidence: 'high',
      matchedWorks: [],
    }
  }

  if (context.payloadSkipped) {
    return {
      ...base,
      action: 'needs_payload_comparison',
      reason: context.payloadSkippedReason,
      confidence: 'low',
      matchedWorks: [],
    }
  }

  const sourceKeyMatches = sourceRecordKey
    ? context.workIndex.bySourceKey.get(sourceRecordKey) || []
    : []

  if (sourceKeyMatches.length === 1) {
    return {
      ...base,
      action: 'link_existing_work_source_key',
      reason: 'exact_source_record_key_match',
      confidence: 'high',
      matchedWorks: [compactWork(sourceKeyMatches[0])],
    }
  }

  if (sourceKeyMatches.length > 1) {
    return {
      ...base,
      action: 'identity_conflict_source_key',
      reason: 'source_record_key_matches_multiple_works',
      confidence: 'medium',
      matchedWorks: sourceKeyMatches.slice(0, 10).map(compactWork),
    }
  }

  const titleMatches = normalizedTitle
    ? context.workIndex.byTitle.get(normalizedTitle) || []
    : []

  if (titleMatches.length === 1) {
    return {
      ...base,
      action: 'link_existing_work_exact_title',
      reason: 'exact_normalized_title_match',
      confidence: 'medium',
      matchedWorks: [compactWork(titleMatches[0])],
    }
  }

  if (titleMatches.length > 1) {
    return {
      ...base,
      action: 'possible_duplicate_title',
      reason: 'normalized_title_matches_multiple_works',
      confidence: 'low',
      matchedWorks: titleMatches.slice(0, 10).map(compactWork),
    }
  }

  if (eligibilityStatus === 'maybe_catalog') {
    return {
      ...base,
      action: 'create_new_work_needs_review',
      reason: 'maybe_catalog_no_existing_work_match',
      confidence: 'low',
      matchedWorks: [],
    }
  }

  return {
    ...base,
    action: 'create_new_work',
    reason: 'eligible_for_catalog_no_existing_work_match',
    confidence: 'medium',
    matchedWorks: [],
  }
}

function buildSummary({ recordsRead, recordsFailed, plans, payload }) {
  const byAction = {}
  const byReason = {}
  const bySource = {}
  const bySourceAction = {}
  const byMediaType = {}
  const byConfidence = {}

  for (const plan of plans) {
    inc(byAction, plan.action)
    inc(byReason, plan.reason)
    inc(bySource, plan.sourceName)
    inc(bySourceAction, `${plan.sourceName}:${plan.action}`)
    inc(byMediaType, plan.sourceMediaType)
    inc(byConfidence, plan.confidence)
  }

  return {
    generatedAt: new Date().toISOString(),
    sourceRecordsRead: recordsRead,
    sourceRecordsFailed: recordsFailed,
    plannedRows: plans.length,
    payloadChecked: !payload.skipped,
    payloadWorks: payload.skipped ? 0 : payload.works.length,
    payloadSkippedReason: payload.skipped ? payload.reason : '',
    byAction: sortCountObject(byAction),
    byReason: sortCountObject(byReason),
    bySource: sortCountObject(bySource),
    bySourceAction: sortCountObject(bySourceAction),
    byMediaType: sortCountObject(byMediaType),
    byConfidence: sortCountObject(byConfidence),
    safety: {
      payloadWrite: false,
      postgresqlWrite: false,
      importerApply: false,
      delete: false,
    },
  }
}

function buildSamples(plans) {
  const byAction = {}

  for (const plan of plans) {
    if (!byAction[plan.action]) byAction[plan.action] = []
    if (byAction[plan.action].length < SAMPLE_LIMIT) byAction[plan.action].push(plan)
  }

  return { byAction }
}

function formatCountTable(title, entries) {
  return [
    `## ${title}`,
    '',
    '| Key | Count |',
    '|---|---:|',
    ...Object.entries(entries).map(([key, count]) => `| ${mdCell(key)} | ${count} |`),
    '',
  ]
}

function formatMarkdown(report) {
  const lines = [
    '# Full Catalog Ingestion Plan v0.1',
    '',
    '## Safety',
    '',
    '- No Payload write.',
    '- No PostgreSQL write.',
    '- No importer apply.',
    '- No delete.',
    '- No `data_local` output should be committed.',
    '',
    '## Summary',
    '',
    `- generatedAt: ${report.summary.generatedAt}`,
    `- sourceRecordsRead: ${report.summary.sourceRecordsRead}`,
    `- sourceRecordsFailed: ${report.summary.sourceRecordsFailed}`,
    `- plannedRows: ${report.summary.plannedRows}`,
    `- payloadChecked: ${report.summary.payloadChecked}`,
    `- payloadWorks: ${report.summary.payloadWorks}`,
    ...(report.summary.payloadSkippedReason ? [`- payloadSkippedReason: ${report.summary.payloadSkippedReason}`] : []),
    '',
    ...formatCountTable('By action', report.summary.byAction),
    ...formatCountTable('By source and action', report.summary.bySourceAction),
    ...formatCountTable('By reason', report.summary.byReason),
    ...formatCountTable('By media type', report.summary.byMediaType),
    '## Sample plans by action',
    '',
    '```json',
    JSON.stringify(report.samples.byAction, null, 2),
    '```',
    '',
    '## Next step',
    '',
    '- Review create/link/duplicate/evidence/quarantine distributions before introducing any write path.',
    '- Use this plan as input for future identity-link planning and a small single-row apply validation PR.',
    '- Do not commit generated files under `data_local`.',
    '',
  ]

  return lines.join('\n')
}

async function main() {
  const args = parseArgs(process.argv.slice(2))

  if (args.help || args.h) {
    usage()
    return
  }

  const sourceRecordsPath = args['source-records'] || DEFAULT_SOURCE_RECORDS
  const outDir = args['out-dir'] || DEFAULT_OUT_DIR
  const baseUrl = args.url || DEFAULT_URL

  if (!fs.existsSync(sourceRecordsPath)) {
    throw new Error(`Source records file not found: ${sourceRecordsPath}\nRun normalize-source-records-v01 first.`)
  }

  const payload = await maybeFetchPayload(baseUrl, Boolean(args['no-payload']))
  const workIndex = buildWorkIndex(payload.works)
  const context = {
    payloadSkipped: payload.skipped,
    payloadSkippedReason: payload.reason || '',
    workIndex,
  }

  const plans = []

  console.error(`[plan] reading source records: ${sourceRecordsPath}`)
  const readResult = await readJsonl(sourceRecordsPath, async (record) => {
    plans.push(planRecord(record, context))
  })

  const summary = buildSummary({
    recordsRead: readResult.rows,
    recordsFailed: readResult.failed,
    plans,
    payload,
  })

  const report = {
    ok: true,
    summary,
    samples: buildSamples(plans),
    outputs: {},
  }

  fs.mkdirSync(outDir, { recursive: true })

  const outPlanJsonl = path.join(outDir, 'full-catalog-ingestion-plan-v01.jsonl')
  const outJson = path.join(outDir, 'full-catalog-ingestion-plan-v01.json')
  const outSummary = path.join(outDir, 'full-catalog-ingestion-plan-v01-summary.json')
  const outMd = path.join(outDir, 'full-catalog-ingestion-plan-v01.md')

  fs.writeFileSync(outPlanJsonl, plans.map((plan) => JSON.stringify(plan)).join('\n') + '\n', 'utf8')
  fs.writeFileSync(outJson, JSON.stringify({ ...report, plans }, null, 2), 'utf8')
  fs.writeFileSync(outSummary, JSON.stringify(summary, null, 2), 'utf8')
  fs.writeFileSync(outMd, formatMarkdown(report), 'utf8')

  report.outputs = {
    jsonl: outPlanJsonl,
    json: outJson,
    summary: outSummary,
    md: outMd,
  }

  console.log(JSON.stringify({
    ok: true,
    summary,
    outputs: report.outputs,
  }, null, 2))
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
